-- Optional manual migration for the existing H2 2.x database.
-- Stop the application and back up backend/data before applying.
-- Default development startup uses Hibernate ddl-auto=update automatically.
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS passkey_user_handle VARCHAR(64);
CREATE UNIQUE INDEX IF NOT EXISTS ux_app_users_passkey_handle ON app_users(passkey_user_handle);
CREATE TABLE IF NOT EXISTS passkey_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    credential_id VARCHAR(1400) NOT NULL UNIQUE,
    public_key_cose VARCHAR(4096) NOT NULL,
    signature_count BIGINT NOT NULL,
    name VARCHAR(80) NOT NULL,
    transports VARCHAR(512),
    backup_eligible BOOLEAN NOT NULL,
    backed_up BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP(6) WITH TIME ZONE,
    version BIGINT NOT NULL,
    CONSTRAINT fk_passkey_user FOREIGN KEY (user_id) REFERENCES app_users(id)
);
CREATE INDEX IF NOT EXISTS idx_passkey_user ON passkey_credentials(user_id);
